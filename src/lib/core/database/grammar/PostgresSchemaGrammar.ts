import type { Blueprint, ColumnBuilder, IndexDefinition } from '../Blueprint.js';
import { Raw } from '../../query/Raw.js';
import { SchemaGrammar } from './SchemaGrammar.js';

const q = (name: string): string => `"${name.replaceAll('"', '""')}"`;
const lit = (value: string): string => `'${value.replaceAll("'", "''")}'`;
const indexName = (index: IndexDefinition, table: string): string =>
  index.name ?? `${table}_${index.fields.join('_')}_${index.unique ? 'unique' : 'index'}`;

const SIMPLE_TYPES: Record<string, string> = {
  'TINYINT(1)': 'BOOLEAN',
  TINYINT: 'SMALLINT',
  SMALLINT: 'SMALLINT',
  YEAR: 'SMALLINT',
  MEDIUMINT: 'INTEGER',
  INT: 'INTEGER',
  INTEGER: 'INTEGER',
  BIGINT: 'BIGINT',
  DOUBLE: 'DOUBLE PRECISION',
  FLOAT: 'REAL',
  DATETIME: 'TIMESTAMPTZ',
  JSON: 'JSONB',
  BLOB: 'BYTEA',
  TINYTEXT: 'TEXT',
  MEDIUMTEXT: 'TEXT',
  LONGTEXT: 'TEXT',
};

function mapType(column: ColumnBuilder): { type: string; enumValues?: string[] } {
  const raw = column.type.trim().replace(/\s+UNSIGNED$/i, '');
  const enumMatch = /^ENUM\((.*)\)$/is.exec(raw);
  if (enumMatch) {
    const values = [...enumMatch[1]!.matchAll(/'((?:[^'\\]|\\.|'')*)'/g)].map((match) =>
      match[1]!.replace(/\\(.)/g, '$1').replace(/''/g, "'"),
    );
    if (!values.length) throw new Error(`Invalid enum definition for column "${column.name}".`);
    return { type: 'VARCHAR(255)', enumValues: values };
  }
  const upper = raw.toUpperCase();
  return { type: SIMPLE_TYPES[upper] ?? raw };
}

function defaultSql(value: unknown, type: string): string {
  if (value instanceof Raw) {
    const raw = value.value.replace(/\s+ON UPDATE\s+CURRENT_TIMESTAMP(?:\(\d*\))?/i, '').trim();
    return raw || 'NULL';
  }
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (typeof value === 'number') return type === 'BOOLEAN' ? (value ? 'TRUE' : 'FALSE') : String(value);
  return lit(String(value));
}

function columnSql(column: ColumnBuilder): string {
  const { type, enumValues } = mapType(column);
  const parts = [q(column.name), type, column.isNullable ? 'NULL' : 'NOT NULL'];
  if (column.hasDefault) parts.push(`DEFAULT ${defaultSql(column.defaultValue, type)}`);
  if (column.isAutoIncrement) parts.push('GENERATED BY DEFAULT AS IDENTITY');
  if (column.isUnique) parts.push('UNIQUE');
  if (enumValues) parts.push(`CHECK (${q(column.name)} IN (${enumValues.map(lit).join(', ')}))`);
  return parts.join(' ');
}

function foreignSql(table: string, column: ColumnBuilder): string | undefined {
  const foreign = column.foreign;
  if (!foreign) return undefined;
  let sql = `CONSTRAINT ${q(`${table}_${column.name}_foreign`)} FOREIGN KEY (${q(column.name)}) REFERENCES ${q(foreign.table)} (${q(foreign.column)})`;
  if (foreign.onDelete) sql += ` ON DELETE ${foreign.onDelete}`;
  if (foreign.onUpdate) sql += ` ON UPDATE ${foreign.onUpdate}`;
  return sql;
}

function createIndex(index: IndexDefinition, table: string): string {
  return `CREATE INDEX ${q(indexName(index, table))} ON ${q(table)} (${index.fields.map(q).join(', ')})`;
}

function commentSql(table: string, column: ColumnBuilder): string[] {
  return column.commentText === undefined
    ? []
    : [`COMMENT ON COLUMN ${q(table)}.${q(column.name)} IS ${lit(column.commentText)}`];
}

export class PostgresSchemaGrammar extends SchemaGrammar {
  readonly dialect = 'pgsql';

  protected override columnDefinition(column: ColumnBuilder): string {
    return columnSql(column);
  }

  protected override indexDefinition(index: IndexDefinition, table: string): string {
    return `CONSTRAINT ${q(indexName(index, table))} UNIQUE (${index.fields.map(q).join(', ')})`;
  }

  protected override foreignKeyDefinition(table: string, column: ColumnBuilder): string | undefined {
    return foreignSql(table, column);
  }

  override createTable(table: string, blueprint: Blueprint): string {
    return this.createStatements(table, blueprint)[0]!;
  }

  override createStatements(table: string, blueprint: Blueprint): string[] {
    const primary = blueprint.columns.filter((column) => column.isPrimary).map((column) => q(column.name));
    const lines = [
      ...blueprint.columns.map(columnSql),
      ...(primary.length ? [`PRIMARY KEY (${primary.join(', ')})`] : []),
      ...blueprint.indexes.filter((index) => index.unique).map((index) => this.indexDefinition(index, table)),
      ...blueprint.columns.map((column) => foreignSql(table, column)).filter((sql): sql is string => Boolean(sql)),
    ];

    return [
      `CREATE TABLE ${q(table)} (\n  ${lines.join(',\n  ')}\n)`,
      ...blueprint.indexes.filter((index) => !index.unique).map((index) => createIndex(index, table)),
      ...blueprint.columns.flatMap((column) => commentSql(table, column)),
    ];
  }

  override alterTable(table: string, blueprint: Blueprint): string[] {
    const alter = `ALTER TABLE ${q(table)}`;
    const statements: string[] = [];

    for (const column of blueprint.columns) {
      if (column.isChange) {
        const { type } = mapType(column);
        const name = q(column.name);
        statements.push(`${alter} ALTER COLUMN ${name} TYPE ${type} USING ${name}::${type}`);
        statements.push(`${alter} ALTER COLUMN ${name} ${column.isNullable ? 'DROP' : 'SET'} NOT NULL`);
        statements.push(
          column.hasDefault
            ? `${alter} ALTER COLUMN ${name} SET DEFAULT ${defaultSql(column.defaultValue, type)}`
            : `${alter} ALTER COLUMN ${name} DROP DEFAULT`,
        );
      } else {
        statements.push(`${alter} ADD COLUMN ${columnSql(column)}`);
      }
      statements.push(...commentSql(table, column));
    }

    for (const index of blueprint.indexes) {
      statements.push(
        index.unique
          ? `${alter} ADD ${this.indexDefinition(index, table)}`
          : createIndex(index, table),
      );
    }
    for (const column of blueprint.columns) {
      const foreign = foreignSql(table, column);
      if (foreign) statements.push(`${alter} ADD ${foreign}`);
    }

    for (const drop of blueprint.drops) {
      let match: RegExpExecArray | null;
      if ((match = /^DROP COLUMN [`"](.+)[`"]$/.exec(drop))) {
        statements.push(`${alter} DROP COLUMN ${q(match[1]!)}`);
      } else if ((match = /^DROP FOREIGN KEY [`"](.+)[`"]$/.exec(drop))) {
        statements.push(`${alter} DROP CONSTRAINT ${q(match[1]!)}`);
      } else if ((match = /^DROP INDEX [`"](.+)[`"]$/.exec(drop))) {
        statements.push(`DROP INDEX IF EXISTS ${q(match[1]!)}`);
        statements.push(`${alter} DROP CONSTRAINT IF EXISTS ${q(match[1]!)}`);
      } else {
        statements.push(`${alter} ${drop.replaceAll('`', '"')}`);
      }
    }
    return statements;
  }
}
