import assert from 'node:assert/strict';
import test from 'node:test';
import { Blueprint } from '../src/lib/core/database/Blueprint.js';
import { PostgresSchemaGrammar } from '../src/lib/core/database/grammar/PostgresSchemaGrammar.js';
import { toPositional } from '../src/lib/core/database/drivers/PostgresDriver.js';
import { PostgresGrammar } from '../src/lib/core/query/grammar/PostgresGrammar.js';
import { Connection } from '../src/lib/core/query/Connection.js';
import type { DatabaseDriver, RawResult } from '../src/lib/core/query/drivers/types.js';

test('Postgres bindings skip quoted strings, comments, and dollar-quoted bodies', () => {
  const sql = "select ?, '?', \"?\", E'escaped \\' ?' -- ?\n/* ? /* ? */ */ where data ?? 'key' and id = ? and body = $$?$$";
  assert.equal(
    toPositional(sql),
    "select $1, '?', \"?\", E'escaped \\' ?' -- ?\n/* ? /* ? */ */ where data ? 'key' and id = $2 and body = $$?$$",
  );
});

test('Postgres schema compilation emits valid table, index, and comment statements', () => {
  const blueprint = new Blueprint('accounts');
  blueprint.id();
  blueprint.string('email').unique();
  blueprint.boolean('active').default(false).comment("User's active flag");
  blueprint.enum('role', ['admin', "user's"]).nullable();
  blueprint.index(['active', 'role']);

  const statements = new PostgresSchemaGrammar().createStatements('accounts', blueprint);
  assert.match(statements[0]!, /"id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(statements[0]!, /"active" BOOLEAN NOT NULL DEFAULT FALSE/);
  assert.match(statements[0]!, /CHECK \("role" IN \('admin', 'user''s'\)\)/);
  assert.doesNotMatch(statements[0]!, /`|COMMENT|INDEX \(/);
  assert.match(statements[1]!, /^CREATE INDEX "accounts_active_role_index" ON "accounts"/);
  assert.equal(statements[2], `COMMENT ON COLUMN "accounts"."active" IS 'User''s active flag'`);
});

test('Postgres query grammar retains dialect-specific operators and syntax', () => {
  const result: RawResult = { rows: [], affectedRows: 0, insertId: undefined };
  const driver: DatabaseDriver = {
    dialect: 'pgsql',
    run: async () => result,
    acquire: async () => ({ run: async () => result, release: () => undefined }),
    close: async () => undefined,
  };
  const connection = new Connection(driver);
  const sql = connection.table('events')
    .where('name', 'ilike', 'test%')
    .whereTime('created_at', '=', '12:30:00')
    .toSql();

  assert.equal(sql, 'select * from "events" where "name" ilike ? and ("created_at")::time = ?');
  assert.equal(new PostgresGrammar().insert('accounts', [{ id: 1 }], { ignore: true }).sql,
    'insert into "accounts" ("id") values (?) on conflict do nothing');
});
